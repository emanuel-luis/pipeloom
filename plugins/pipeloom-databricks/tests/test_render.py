def test_PLD004_more_than_ten_serverless_environments(
    models_plan: Models, deploy: Deploy, render: Render
) -> None:
    names = [f"m{i:02d}" for i in range(12)]
    plan = models_plan(
        {
            "models/m.yml": "models:\n"
            + "".join(f"  - {{name: {n}, sql: 'select 1 as x'}}\n" for n in names)
        }
    )
    compute = {f"c{i:02d}": {"kind": "serverless"} for i in range(12)}
    rules = [{"select": [f"name:{n}"], "compute": f"c{i:02d}"} for i, n in enumerate(names)]
    job, report = render(
        deploy(plan, compute={"default": {"kind": "serverless"}, **compute}, compute_rules=rules)
    )
    assert job is None and _codes(report) == ["PLD004"]
    assert "13 serverless environments" in report.sorted()[0].message
    # Ten are fine: the default plus nine used.
    ok, report = render(
        deploy(
            plan, compute={"default": {"kind": "serverless"}, **compute}, compute_rules=rules[:9]
        )
    )
    assert ok is not None and _codes(report) == []
    assert len(to_json(ok.settings)["environments"]) == 10


