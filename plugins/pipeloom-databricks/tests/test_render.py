def test_pinned_distributions_follow_the_plan(shop: Plan, deploy: Deploy, render: Render) -> None:
    plan = deploy(shop)
    plugins = dict(plan.metadata.plugins)
    plugins["engines"] = plugins["engines"].model_copy(
        update={"distribution": "pipeloom-spark", "version": "9.9.9"}
    )
    plan = plan.model_copy(
        update={"metadata": plan.metadata.model_copy(update={"plugins": plugins})}
    )
    job, _ = render(plan)
    assert job is not None
    env = to_json(job.settings)["environments"][0]
    assert env["spec"]["dependencies"] == [
        "pipeloom==1.2.3",
        "pipeloom-databricks==1.2.3",
        "pipeloom-spark==9.9.9",
    ]
    custom, _ = render(
        deploy(shop, compute={"default": {"kind": "serverless", "dependencies": ["x==1"]}})
    )
    assert custom is not None
    assert to_json(custom.settings)["environments"][0]["spec"]["dependencies"] == ["x==1"]


