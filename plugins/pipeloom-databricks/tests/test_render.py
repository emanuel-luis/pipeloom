def _render_in_a_process(flags: list[str], seed: str | None) -> bytes:
    shop = Path(__file__).resolve().parents[3] / "tests" / "fixtures" / "shop"
    env = {k: v for k, v in os.environ.items() if k != "PYTHONHASHSEED"}
    if seed is not None:
        env["PYTHONHASHSEED"] = seed
    proc = subprocess.run(
        [sys.executable, *flags, "-c", DETERMINISM, str(shop)],
        capture_output=True,
        env=env,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr.decode("utf-8", "replace")
    return proc.stdout


def test_output_is_byte_identical_across_processes_and_hash_seeds() -> None:
    # `-I` ignores PYTHONHASHSEED (and picks a random seed each time), so the two seeded runs
    # use `-s`; the `-I` run proves nothing in the environment or user site leaks in.
    first = _render_in_a_process(["-s"], "1")
    second = _render_in_a_process(["-s"], "2")
    isolated = _render_in_a_process(["-I"], None)
    assert first.startswith(b"{")
    assert first == second == isolated
