def _codes(report: Report) -> list[str]:
    return [d.code for d in report.sorted()]


@pytest.mark.parametrize("name", sorted(SCENARIOS))
def test_job_goldens(
    name: str, shop: Plan, deploy: Deploy, render: Render, golden: Callable[[str, bytes], None]
) -> None:
    job, report = render(deploy(shop, **SCENARIOS[name]))
    assert job is not None and _codes(report) == []
    doc = to_json(job.settings)
    golden(f"{name}.json", to_json_bytes(doc))
    bundle = to_bundle_yaml(job.settings.name, doc, HEADER)
    golden(f"{name}.yml", bundle)
    # The bundle is the same job as YAML.
    assert yaml.safe_load(bundle)["resources"]["jobs"][job.settings.name] == doc


def test_ephemeral_submit_golden(
    shop: Plan,
    deploy: Deploy,
    locs: Locations,
    versions: dict[str, str],
    golden: Callable[..., None],
) -> None:
    report = Report()
    spec = render_submit(
        deploy(shop),
        "main",
        locs,
        report,
        run_id="dbx-42",
        full_refresh=True,
        start_ms=1_700_000_000_000,
        versions=versions,
    )
    assert spec is not None and _codes(report) == []
    doc = to_json(spec)
    assert list(doc) == ["run_name", "tasks", "environments", "queue"]
    golden("submit.json", to_json_bytes(doc))
    args = json.dumps(doc["tasks"])
    assert "--job-id" not in args and "--job-run-id" not in args and "job_cluster_key" not in args
    assert "--run-id=dbx-42" in args and "--full-refresh=true" in args
    assert "--start-ms=1700000000000" in args


def test_job_shape(shop: Plan, deploy: Deploy, render: Render) -> None:
    job, _ = render(deploy(shop, **SCENARIOS["job_cluster"]))
    assert job is not None
    doc = to_json(job.settings)
    assert list(doc)[:7] == [
        "name",
        "tags",
        "parameters",
        "max_concurrent_runs",
        "queue",
        "environments",
        "job_clusters",
    ]
    assert list(doc)[-2:] == ["tasks", "schedule"]
    assert doc["name"] == "pipeloom_shop_main_ci"
    tags = doc["tags"]
    assert isinstance(tags, dict)
    assert tags["pipeloom_job"] == "shop.main.ci" and tags["team"] == "data"
    assert tags["pipeloom_settings_hash"] == job.settings_hash == settings_hash(doc)
    tasks = doc["tasks"]
    assert isinstance(tasks, list)
    keys = [t["task_key"] for t in tasks]
    assert keys == sorted(keys[:-1]) + ["pipeloom__finalize"]
    by_key = {t["task_key"]: t for t in tasks}
    assert by_key["fct_orders"]["job_cluster_key"] == "pipeloom_big"
    assert "libraries" in by_key["fct_orders"] and "environment_key" not in by_key["fct_orders"]
    assert by_key["stg_orders"]["environment_key"] == "pipeloom_default"
    final = by_key["pipeloom__finalize"]
    assert final["run_if"] == "ALL_DONE" and final["max_retries"] == 1
    assert final["timeout_seconds"] == 1800
    assert final["depends_on"] == [{"task_key": "dim_customers"}, {"task_key": "rpt_revenue"}]
    params = by_key["fct_orders"]["python_wheel_task"]["parameters"]
    assert params[:2] == ["unit", "--project-dir=/Workspace/pipeloom/shop"]
    assert "--unit=fct_orders" in params and "--run-id={{job.parameters.pipeloom_run_id}}" in params
    assert params[-1] == "--start-ms={{job.start_time.timestamp_ms}}"
    assert by_key["fct_orders"]["python_wheel_task"]["entry_point"] == "pipeloom_databricks_task"
    assert [a for a in final["python_wheel_task"]["parameters"] if "task" in a or "unit" in a] == []


