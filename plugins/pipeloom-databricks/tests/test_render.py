def test_retries_and_timeouts_come_from_the_models(
    models_plan: Models, deploy: Deploy, render: Render
) -> None:
    plan = models_plan(
        {
            "models/m.yml": (
                "models:\n"
                "  - {name: a, sql: 'select 1 as x', tags: [g], retries: 2, retry_delay: 5s, timeout: 10m}\n"
                "  - {name: b, sql: 'select 1 as x', tags: [g], retries: 3, retry_delay: 9s, timeout: 1m}\n"
                "  - {name: c, sql: 'select 1 as x', tags: [h], retries: 1, retry_delay: 2s}\n"
                "  - {name: d, sql: 'select 1 as x'}\n"
            )
        }
    )
    job, _ = render(deploy(plan))
    assert job is not None
    by_key = {t["task_key"]: t for t in to_json(job.settings)["tasks"]}
    assert by_key["a"]["max_retries"] == 2 and by_key["a"]["min_retry_interval_millis"] == 5000
    assert by_key["a"]["timeout_seconds"] == 600 + 30 + 300
    assert "timeout_seconds" not in by_key["c"] and by_key["c"]["max_retries"] == 1
    assert by_key["d"]["max_retries"] == 0 and "min_retry_interval_millis" not in by_key["d"]
    grouped, _ = render(deploy(plan, task_grouping="by_tag"))
    assert grouped is not None
    g = {t["task_key"]: t for t in to_json(grouped.settings)["tasks"]}
    assert g["tag_g"]["max_retries"] == 3 and g["tag_g"]["min_retry_interval_millis"] == 9000
    assert g["tag_g"]["timeout_seconds"] == (600 + 30) + (60 + 30) + 300
    assert "timeout_seconds" not in g["tag_h"]


def test_999_units_render_and_1000_are_PLD001(
    models_plan: Models, deploy: Deploy, render: Render
) -> None:
    lines = [f"  - {{name: m{i:04d}, sql: 'select 1 as x'}}" for i in range(1000)]
    plan = deploy(
        models_plan({"models/m.yml": "models:\n" + "\n".join(lines) + "\n"}),
        pipelines={"all": {}, "most": {"exclude": ["name:m0999"]}},
    )
    job, report = render(plan, "most")
    assert job is not None and _codes(report) == []
    assert len(to_json(job.settings)["tasks"]) == 1000
    none, report = render(plan, "all")
    assert none is None and _codes(report) == ["PLD001"]


