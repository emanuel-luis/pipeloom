"""`pipeloom databricks bundle`: every flag, bundle root detection, exit codes and --check."""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

import pytest
import yaml
from click.testing import CliRunner, Result

from pipeloom.cli import main
from pipeloom.plan.manifest import manifest_bytes
from pipeloom_databricks.cli import databricks

Sim = Any
JOB = "pipeloom_sim_main_prod"
EXTRA = "pipeloom_sim_extra_prod"


@pytest.fixture
def layout(sim: Callable[..., Sim], tmp_path: Path) -> tuple[Sim, Path, Path]:
    """The sim project in tmp/proj, a bundle root at tmp (databricks.yml) and an output folder."""
    s = sim()
    (tmp_path / "databricks.yml").write_text("bundle: {name: sim}\n", encoding="utf-8")
    return s, tmp_path, tmp_path / "resources"


def bundle(s: Sim, *args: str, env: dict[str, str] | None = None) -> Result:
    argv = ["bundle", "--project-dir", str(s.root), "--target", "prod", *args]
    return CliRunner().invoke(databricks, argv, env=env)


def test_writes_one_job_and_one_stable_manifest_per_pipeline(
    layout: tuple[Sim, Path, Path],
) -> None:
    s, _, out = layout
    r = bundle(s, "--out", str(out))
    assert r.exit_code == 0, r.stderr
    names = sorted(p.name for p in out.iterdir())
    assert names == [
        f"{EXTRA}.job.yml",
        f"{EXTRA}.manifest.json",
        f"{JOB}.job.yml",
        f"{JOB}.manifest.json",
    ]
    assert sorted(r.stdout.split()) == sorted(p.as_posix() for p in out.iterdir())

    text = (out / f"{JOB}.job.yml").read_text(encoding="utf-8")
    assert text.startswith("# Generated by pipeloom-databricks ")
    assert "# Project: sim. Pipeline: main. Target: prod." in text
    assert "# Do not edit" in text
    job = yaml.safe_load(text)["resources"]["jobs"][JOB]
    assert job["name"] == JOB
    first = next(t for t in job["tasks"] if t["task_key"] == "a")
    params = first["python_wheel_task"]["parameters"]
    assert "--project-dir=${workspace.file_path}/proj" in params
    assert f"--manifest=${{workspace.file_path}}/resources/{JOB}.manifest.json" in params
    assert "--run-id={{job.parameters.pipeloom_run_id}}" in params

    shipped = (out / f"{JOB}.manifest.json").read_bytes()
    assert shipped == manifest_bytes(s.plan, stable=True)
    assert json.loads(shipped)["metadata"]["generated_at"] == ""


def test_pipeline_flag_is_repeatable_and_unknown_names_fail(layout: tuple[Sim, Path, Path]) -> None:
    s, _, out = layout
    assert bundle(s, "--out", str(out), "--pipeline", "extra").exit_code == 0
    assert sorted(p.name for p in out.iterdir()) == [f"{EXTRA}.job.yml", f"{EXTRA}.manifest.json"]
    both = bundle(s, "--out", str(out), "--pipeline", "main", "--pipeline", "extra")
    assert both.exit_code == 0 and len(list(out.iterdir())) == 4
    bad = bundle(s, "--out", str(out / "x"), "--pipeline", "nope")
    assert bad.exit_code == 1 and "PLD004" in bad.stderr
    assert not (out / "x").exists()


def test_check_writes_nothing_and_lists_the_files_that_differ(
    layout: tuple[Sim, Path, Path],
) -> None:
    s, _, out = layout
    missing = bundle(s, "--out", str(out), "--check")
    assert missing.exit_code == 1 and not out.exists()
    assert len(missing.stdout.split()) == 4
    assert bundle(s, "--out", str(out)).exit_code == 0
    clean = bundle(s, "--out", str(out), "--check")
    assert clean.exit_code == 0 and clean.stdout == ""
    stale = out / f"{JOB}.job.yml"
    stale.write_bytes(stale.read_bytes() + b"# edited\n")
    drift = bundle(s, "--out", str(out), "--check")
    assert drift.exit_code == 1 and drift.stdout.split() == [stale.as_posix()]
    assert stale.read_bytes().endswith(b"# edited\n")  # not rewritten


def test_the_output_is_byte_identical_between_runs(layout: tuple[Sim, Path, Path]) -> None:
    s, _, out = layout
    bundle(s, "--out", str(out))
    before = {p.name: p.read_bytes() for p in out.iterdir()}
    bundle(s, "--out", str(out))
    assert {p.name: p.read_bytes() for p in out.iterdir()} == before


def test_bundle_root_is_the_nearest_ancestor_with_databricks_yml(
    layout: tuple[Sim, Path, Path],
) -> None:
    s, root, _ = layout
    nested = root / "resources" / "deep" / "er"
    assert bundle(s, "--out", str(nested)).exit_code == 0
    job = yaml.safe_load((nested / f"{JOB}.job.yml").read_text(encoding="utf-8"))
    params = job["resources"]["jobs"][JOB]["tasks"][0]["python_wheel_task"]["parameters"]
    assert f"--manifest=${{workspace.file_path}}/resources/deep/er/{JOB}.manifest.json" in params


def test_no_bundle_root_exits_2(sim: Callable[..., Sim], tmp_path: Path) -> None:
    s = sim()
    r = bundle(s, "--out", str(tmp_path / "out"))
    assert r.exit_code == 2 and "no databricks.yml" in r.stderr
    assert not (tmp_path / "out").exists()


def test_bundle_root_flag_and_paths_outside_it_exit_2(
    sim: Callable[..., Sim], tmp_path: Path
) -> None:
    s = sim()
    ok = bundle(s, "--out", str(tmp_path / "gen"), "--bundle-root", str(tmp_path))
    assert ok.exit_code == 0  # no databricks.yml needed with the flag
    inner = tmp_path / "gen"
    outside = bundle(s, "--out", str(inner / "o"), "--bundle-root", str(inner))
    assert outside.exit_code == 2 and "inside the bundle" in outside.stderr  # the project is above
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    out = bundle(s, "--out", str(tmp_path / "gen"), "--bundle-root", str(elsewhere))
    assert out.exit_code == 2


def test_a_project_at_the_bundle_root_uses_the_bare_variable(
    sim: Callable[..., Sim],
) -> None:
    s = sim()
    (s.root / "databricks.yml").write_text("bundle: {name: sim}\n", encoding="utf-8")
    out = s.root / "res"
    assert bundle(s, "--out", str(out)).exit_code == 0
    text = (out / f"{JOB}.job.yml").read_text(encoding="utf-8")
    assert "--project-dir=${workspace.file_path}\n" in text.replace("'", "").replace('"', "") + "\n"
    assert f"--manifest=${{workspace.file_path}}/res/{JOB}.manifest.json" in text


def test_error_diagnostics_exit_1_and_write_nothing(layout: tuple[Sim, Path, Path]) -> None:
    s, _, out = layout
    yml = s.root / "pipeloom.yml"
    yml.write_text(
        yml.read_text(encoding="utf-8").replace(s.artifacts.as_posix(), "target"), encoding="utf-8"
    )
    r = bundle(s, "--out", str(out))
    assert r.exit_code == 1 and "PLD004" in r.stderr
    assert not out.exists()
    unknown = CliRunner().invoke(
        databricks,
        ["bundle", "--project-dir", str(s.root), "--target", "nope", "--out", str(out)],
    )
    assert unknown.exit_code == 1 and "PLR204" in unknown.stderr


def test_target_comes_from_the_environment_and_vars_are_accepted(
    layout: tuple[Sim, Path, Path],
) -> None:
    s, _, out = layout
    r = CliRunner().invoke(
        databricks,
        ["bundle", "--project-dir", str(s.root), "--out", str(out), "--vars", '{"x": 1}'],
        env={"PIPELOOM_TARGET": "prod"},
    )
    assert r.exit_code == 0, r.stderr
    bad = CliRunner().invoke(
        databricks, ["bundle", "--project-dir", str(s.root), "--out", str(out), "--vars", "[1]"]
    )
    assert bad.exit_code == 2


def test_plugin_flag_loads_the_renderer_when_autoload_is_off(
    layout: tuple[Sim, Path, Path],
) -> None:
    s, _, out = layout
    r = bundle(
        s,
        "--out",
        str(out),
        "--plugin",
        "pipeloom_databricks.spec:RENDERER_SPEC",
        env={"PIPELOOM_DISABLE_PLUGIN_AUTOLOAD": "1"},
    )
    assert r.exit_code == 0, r.stderr
    without = bundle(s, "--out", str(out), env={"PIPELOOM_DISABLE_PLUGIN_AUTOLOAD": "1"})
    assert without.exit_code != 0


def test_log_format_json_prints_one_event_per_line(layout: tuple[Sim, Path, Path]) -> None:
    s, _, out = layout
    r = bundle(s, "--out", str(out), "--log-format", "json")
    events = [json.loads(line) for line in r.stderr.splitlines() if line.startswith("{")]
    assert events and events[0]["type"] == "invocation.started"


def test_the_group_is_a_pipeloom_command_through_its_entry_point() -> None:
    listing = CliRunner().invoke(main, ["--help"])
    assert "databricks" in listing.stdout and "Added by pipeloom-databricks" in listing.stdout
    helped = CliRunner().invoke(main, ["databricks", "bundle", "--help"])
    assert helped.exit_code == 0 and "--bundle-root" in helped.stdout
    off = CliRunner().invoke(main, ["--help"], env={"PIPELOOM_DISABLE_PLUGIN_AUTOLOAD": "1"})
    assert "databricks" not in off.stdout
